/* Workflow builder: trigger -> action -> condition steps, export + localStorage */
var WF_KEY = 'aiah_workflow_v1';
var wfSteps = [];

function wfLoad() {
  try {
    var raw = localStorage.getItem(WF_KEY);
    if (raw) wfSteps = JSON.parse(raw) || [];
  } catch (e) { wfSteps = []; }
  wfRender();
}
function wfSave() {
  try { localStorage.setItem(WF_KEY, JSON.stringify(wfSteps)); } catch (e) {}
}
function wfAdd() {
  var type = document.getElementById('wf-type').value;
  var name = document.getElementById('wf-name').value.trim();
  var detail = document.getElementById('wf-detail').value.trim();
  if (!name) { alert('Give the step a name first.'); return; }
  wfSteps.push({ type: type, name: name, detail: detail });
  document.getElementById('wf-name').value = '';
  document.getElementById('wf-detail').value = '';
  wfSave(); wfRender();
}
function wfDel(i) { wfSteps.splice(i, 1); wfSave(); wfRender(); }
function wfMove(i, dir) {
  var j = i + dir;
  if (j < 0 || j >= wfSteps.length) return;
  var t = wfSteps[i]; wfSteps[i] = wfSteps[j]; wfSteps[j] = t;
  wfSave(); wfRender();
}
function wfClear() {
  if (!wfSteps.length || confirm('Clear all workflow steps?')) {
    wfSteps = []; wfSave(); wfRender();
  }
}
var TYPE_LABEL = { trigger: '⚡ TRIGGER', action: '🔧 ACTION', condition: '🔀 CONDITION' };
function wfRender() {
  var box = document.getElementById('wf-list');
  var count = document.getElementById('wf-count');
  if (count) count.textContent = wfSteps.length + ' step' + (wfSteps.length === 1 ? '' : 's');
  if (!box) return;
  if (!wfSteps.length) {
    box.innerHTML = '<p style="color:var(--muted)">No steps yet. Add your first trigger above — e.g. "New email arrives".</p>';
    return;
  }
  var html = '';
  for (var i = 0; i < wfSteps.length; i++) {
    var s = wfSteps[i];
    html += '<div class="step"><span class="badge">' + TYPE_LABEL[s.type] + '</span>' +
      '<div class="grow"><b>' + (i + 1) + '. ' + esc(s.name) + '</b>' +
      (s.detail ? '<div style="color:var(--muted);font-size:.9rem">' + esc(s.detail) + '</div>' : '') + '</div>' +
      '<button class="del" onclick="wfMove(' + i + ',-1)" title="Move up">↑</button>' +
      '<button class="del" onclick="wfMove(' + i + ',1)" title="Move down">↓</button>' +
      '<button class="del" onclick="wfDel(' + i + ')" title="Delete">✕</button></div>';
    if (i < wfSteps.length - 1) html += '<div style="text-align:center;color:var(--accent);font-size:1.3rem">↓</div>';
  }
  box.innerHTML = html;
}
function wfExport() {
  if (!wfSteps.length) { alert('Add some steps first.'); return; }
  var lines = ['AUTOMATION WORKFLOW CHECKLIST', 'Generated by AIAutomationHub', ''];
  for (var i = 0; i < wfSteps.length; i++) {
    var s = wfSteps[i];
    lines.push('[ ] Step ' + (i + 1) + ' [' + s.type.toUpperCase() + '] ' + s.name);
    if (s.detail) lines.push('    → ' + s.detail);
  }
  lines.push('', 'Tool suggestions: Zapier / Make / n8n for triggers+actions, ChatGPT API for AI steps.');
  var txt = lines.join('\n');
  copyText(txt, document.getElementById('wf-export-btn'));
  var prev = document.getElementById('wf-output');
  if (prev) { prev.style.display = 'block'; prev.textContent = txt; }
}
document.addEventListener('DOMContentLoaded', wfLoad);
